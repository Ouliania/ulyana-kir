/** Twin path for lang switch: /foo ↔ /ru/foo */
export function twinPath(pathname: string, target: Locale): string {
  const clean = pathname.replace(/\/$/, '') || '/';
  if (target === 'ru') {
    if (clean === '/' || clean === '') return '/ru/';
    if (clean.startsWith('/ru')) return clean.endsWith('/') ? clean : `${clean}/`;
    return `/ru${clean}/`;
  }
  // target en
  if (clean === '/ru' || clean.startsWith('/ru/')) {
    const rest = clean.replace(/^\/ru/, '') || '/';
    return rest.endsWith('/') || rest === '/' ? rest : `${rest}/`;
  }
  return clean === '/' ? '/' : `${clean}/`;
}

export function localeFromPath(pathname: string): Locale {
  return pathname === '/ru' || pathname.startsWith('/ru/') ? 'ru' : 'en';
}
